#!/bin/bash

# Rebuilds the master index from all topic READMEs
# Usage: ./rebuild_index.sh

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESEARCH_DIR="$(dirname "$SCRIPT_DIR")"
TOPICS_DIR="$RESEARCH_DIR/topics"
INDEX_FILE="$RESEARCH_DIR/_meta/index.md"

echo "Rebuilding index from topics..."

# Start the index file
cat > "$INDEX_FILE" << 'HEADER'
# Research Index

Master index of all research topics.

## Topics

| Topic | Status | Tags | Last Updated |
|-------|--------|------|--------------|
HEADER

# Process each topic
for topic_dir in "$TOPICS_DIR"/*/; do
    if [ -d "$topic_dir" ]; then
        topic_name=$(basename "$topic_dir")
        readme="$topic_dir/README.md"

        if [ -f "$readme" ]; then
            # Extract status (look for **Status**: line)
            status=$(grep -oP '\*\*Status\*\*:\s*\K[^\n]*' "$readme" 2>/dev/null | head -1 || echo "Unknown")

            # Extract tags (look for **Tags**: line)
            tags=$(grep -oP '\*\*Tags\*\*:\s*\K[^\n]*' "$readme" 2>/dev/null | head -1 || echo "")

            # Get last modified date
            last_updated=$(date -r "$readme" +%Y-%m-%d 2>/dev/null || echo "Unknown")

            echo "| [$topic_name](../topics/$topic_name/) | $status | $tags | $last_updated |" >> "$INDEX_FILE"
        fi
    fi
done

# Add the rest of the index structure
cat >> "$INDEX_FILE" << 'FOOTER'

## By Status

### In Progress
-

### Completed
-

### Planned
-

## By Category

### Technical
-

### Scientific
-

### Business
-

### General
-

---

*Auto-generated by `./scripts/rebuild_index.sh`*
FOOTER

echo "Index rebuilt at: $INDEX_FILE"
